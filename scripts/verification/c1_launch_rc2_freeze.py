"""Build or check the RC2 release identity.

Usage
-----
    python scripts/verification/c1_launch_rc2_freeze.py          # write manifest + digest
    python scripts/verification/c1_launch_rc2_freeze.py --check  # verify current identity

Writing is deliberate: it is the act of freezing. ``--check`` never writes.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.research.c1_film_launch_rc2 import release_identity_rc2 as rid  # noqa: E402


def freeze() -> dict:
    manifest = rid.build_manifest(rid.REQUIRED_COVERAGE)
    text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    rid.MANIFEST_PATH.write_text(text, encoding="utf-8")

    digest = rid.compute_release_digest(manifest)
    manifest_sha = rid.sha256_bytes(rid.MANIFEST_PATH.read_bytes())

    lines = [
        "# C1 launch release identity — RC2. Generated by c1_launch_rc2_freeze.py.",
        f"release_id={rid.RELEASE_ID}",
        f"study_id={rid.STUDY_ID}",
        f"release_digest={digest}",
        f"manifest_sha256={manifest_sha}",
        f"manifest_path=src/research/c1_film_launch_rc2/{rid.MANIFEST_NAME}",
        f"supersedes_release_id={rid.RC1_RELEASE_ID}",
        f"supersedes_release_digest={rid.RC1_RELEASE_DIGEST}",
        f"supersedes_manifest_sha256={rid.RC1_MANIFEST_SHA256}",
        f"protocol_sha256={rid.PROTOCOL_SHA256}",
        f"architecture_sha256={rid.ARCHITECTURE_SHA256}",
        f"canonicalisation={rid.CANONICALISATION}",
        f"digest_rule={rid.DIGEST_RULE}",
        f"bound_source_count={len(manifest['bound_sources'])}",
        "trust_store=EXTERNAL_INSTITUTIONAL_UNPROVISIONED",
        "host_clock_trust=NOT_ESTABLISHED",
        "scientific_execution=NOT_AUTHORIZED",
    ]
    rid.DIGEST_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"release_digest": digest, "manifest_sha256": manifest_sha,
            "bound_source_count": len(manifest["bound_sources"])}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the current identity instead of writing it")
    args = parser.parse_args()

    if args.check:
        try:
            report = rid.verify_release_rc2()
        except rid.ReleaseIdentityError as exc:
            print(f"RELEASE_NOT_CURRENT:{exc}")
            return 1
        print(f"release_digest={report['release_digest']}")
        print(f"manifest_file_sha256={report['manifest_file_sha256']}")
        print(f"bound_source_count={report['bound_source_count']}")
        print(f"supersedes_release_digest={report['supersedes']['release_digest']}")
        print("RELEASE_CURRENT")
        return 0

    result = freeze()
    print(f"release_digest={result['release_digest']}")
    print(f"manifest_sha256={result['manifest_sha256']}")
    print(f"bound_source_count={result['bound_source_count']}")
    print("RELEASE_FROZEN")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
