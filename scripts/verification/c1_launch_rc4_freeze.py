"""Build or check the RC4 release identity.

    python scripts/verification/c1_launch_rc4_freeze.py          # write manifest + digest
    python scripts/verification/c1_launch_rc4_freeze.py --check  # verify current identity
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.research.c1_film_launch_rc4 import release_identity_rc4 as rid  # noqa: E402


def freeze() -> dict:
    if rid.MANIFEST_PATH.exists() or rid.DIGEST_PATH.exists():
        raise SystemExit("RC4 identity already published; refusing to overwrite.")
    manifest = rid.build_manifest(rid.REQUIRED_COVERAGE)
    rid.MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n",
                                 encoding="utf-8")
    digest = rid.compute_release_digest(manifest)
    manifest_sha = rid.sha256_bytes(rid.MANIFEST_PATH.read_bytes())
    lines = [
        "# C1 launch release identity - RC4. Generated by c1_launch_rc4_freeze.py.",
        f"release_id={rid.RELEASE_ID}",
        f"study_id={rid.STUDY_ID}",
        f"release_digest={digest}",
        f"manifest_sha256={manifest_sha}",
        f"code_digest={manifest['code_digest']}",
        f"manifest_path={rid.PACKAGE_REL}/{rid.MANIFEST_NAME}",
        *[f"supersedes_{k}_release_digest={v['release_digest']}"
          for k, v in rid.PREDECESSORS.items()],
        f"protocol_sha256={rid.PROTOCOL_SHA256}",
        f"architecture_sha256={rid.ARCHITECTURE_SHA256}",
        f"digest_rule={rid.DIGEST_RULE}",
        f"bound_source_count={len(manifest['bound_sources'])}",
        "trust_store=EXTERNAL_INSTITUTIONAL_UNPROVISIONED",
        "authorization_model=DECISION_I",
        "institutional_approval=PENDING",
        "host_clock_trust=NOT_ESTABLISHED",
        "scientific_execution=NOT_AUTHORIZED",
    ]
    rid.DIGEST_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"release_digest": digest, "manifest_sha256": manifest_sha}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        print("C1 RC4 identity OK:", rid.verify_release_rc4()["release_digest"])
        return 0
    print("Frozen C1 RC4 release:", freeze()["release_digest"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
