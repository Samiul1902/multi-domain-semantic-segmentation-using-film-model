        "    axes[1, 0].add_patch(patches.Rectangle((x1, y1), x2 - x1, y2 - y1, fill=False, edgecolor='cyan', lw=2))\n",
        "axes[1, 0].set_title('D. Canonical Stage-4D Proposal Boxes')\n",
        "axes[1, 1].imshow(raw_img, cmap='gray'); axes[1, 1].contour(mask_prd, colors='orange', linewidths=1.5); axes[1, 1].set_title('E. Regional-Refined Prediction')\n",
        "axes[1, 2].imshow(raw_img, cmap='gray'); axes[1, 2].contour(raw_mask, colors='lime', linewidths=1.5); axes[1, 2].contour(mask_prd, colors='orange', linewidths=1.5); axes[1, 2].set_title('F. Final Prediction Overlay')\n",
        "for ax in axes.flat: ax.axis('off')\n",
        "plt.tight_layout()\n",
        "\n",
        "demo_out_path = PROJECT_ROOT / 'reports/figures/phase14_part3c/phase14_part3_demo_visualization.png'\n",
