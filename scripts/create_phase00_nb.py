def get_sha256(path):
    if not path.exists():
        return "FILE_NOT_FOUND"
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()

canon_p = ROOT / 'notebooks/13_phase14_regional_refiner_diagnostic.ipynb'
canon_sha = get_sha256(canon_p)
expected_sha = "b5b329d1d100138db640e4a3e91069a4008a434d998945646bc7a4522c040948"

print(f"Canonical Phase 14 Notebook SHA-256 Verification:")
